// Fetch real tracks from Jamendo API
export const loadRealTracksFromJamendo = async (): Promise<Track[]> => {
  console.log('[v0] Loading real tracks from Jamendo...');
  
  const genreMap = [
    { genres: ['jazz', 'jazzfunk'], genre: 'jazz', limit: 8 },
    { genres: ['funk', 'soul'], genre: 'funk', limit: 8 },
    { genres: ['soul', 'rnb'], genre: 'soul', limit: 7 },
    { genres: ['reggae', 'dub'], genre: 'reggae', limit: 7 },
    { genres: ['afrobeat', 'worldmusic', 'african'], genre: 'afrobeat', limit: 6 }
  ];
  
  const allTracks: Track[] = [];
  
  for (const { genres, genre, limit } of genreMap) {
    try {
      const jamendoTracks = await searchJamendoByGenre(genres, limit);
      
      jamendoTracks.forEach((jTrack, index) => {
        // Assign rarity based on position (earlier = rarer)
        const rarity = Math.max(7, 10 - Math.floor(index / 2));
        
        const track = convertJamendoTrack(jTrack, genre, rarity);
        allTracks.push(track);
      });
    } catch (error) {
      console.error(`[v0] Failed to load ${genre} tracks from Jamendo:`, error);
    }
  }
  
  console.log('[v0] Loaded', allTracks.length, 'real tracks from Jamendo');
  return allTracks;
};

// Fetch real audio previews and album covers from Deezer/iTunes
// Optimized for faster initial load - only loads first batch
export const loadRealAudioFromDeezer = async (
  tracks: Track[], 
  maxInitial = 40,
  onProgress?: (loaded: number, total: number) => void
): Promise<Track[]> => {
  console.log('[v0] Fetching real audio and album covers...');
  
  const BATCH_SIZE = 10;
  const DELAY_MS = 50;
  const results: Track[] = [];
  
  const tracksToLoad = tracks.slice(0, maxInitial);
  const remainingTracks = tracks.slice(maxInitial);
  
  for (let i = 0; i < tracksToLoad.length; i += BATCH_SIZE) {
    const batch = tracksToLoad.slice(i, i + BATCH_SIZE);
    
    const batchResults = await Promise.all(
      batch.map(async (track) => {
        try {
          const deezerData = await searchDeezerTrack(track.artist, track.title);
          
          return {
            ...track,
            audioUrl: deezerData.previewUrl || track.audioUrl,
            albumArt: deezerData.albumCover || track.albumArt
          };
        } catch (error) {
          console.error(`[v0] Failed to load data for ${track.artist} - ${track.title}:`, error);
        }
        return track;
      })
    );
    
    results.push(...batchResults);
    
    // Report progress
    if (onProgress) {
      onProgress(results.length, tracks.length);
    }
    
    if (i + BATCH_SIZE < tracksToLoad.length) {
      await new Promise(resolve => setTimeout(resolve, DELAY_MS));
    }
  }
  
  // Add remaining tracks without loading audio (lazy load later)
  results.push(...remainingTracks.map(track => ({ ...track })));
  
  // Final progress update
  if (onProgress) {
    onProgress(tracks.length, tracks.length);
  }
  
  const audioCount = results.filter(t => t.audioUrl.startsWith('http')).length;
  console.log('[v0] Loaded', audioCount, 'audio previews (lazy loading rest)');
  
  return results;
};

// Load audio for additional tracks (for lazy loading)
export const loadAudioForTracks = async (tracks: Track[]): Promise<Track[]> => {
  const BATCH_SIZE = 10;
  const DELAY_MS = 30;
  const results: Track[] = [...tracks];
  
  for (let i = 0; i < tracks.length; i += BATCH_SIZE) {
    const batch = tracks.slice(i, i + BATCH_SIZE);
    
    await Promise.all(
      batch.map(async (track, idx) => {
        if (results[i + idx] && !results[i + idx].audioUrl.startsWith('http')) {
          try {
            const deezerData = await searchDeezerTrack(track.artist, track.title);
            results[i + idx] = {
              ...results[i + idx]!,
              audioUrl: deezerData.previewUrl || results[i + idx]!.audioUrl,
              albumArt: deezerData.albumCover || results[i + idx]!.albumArt
            };
          } catch (error) {
            // Silent fail for lazy loading
          }
        }
      })
    );
    
    if (i + BATCH_SIZE < tracks.length) {
      await new Promise(resolve => setTimeout(resolve, DELAY_MS));
    }
  }
  
  return results;
};

// Fetch real album covers from iTunes API
export const loadRealAlbumCovers = async (tracks: Track[]): Promise<Track[]> => {
  const tracksWithCovers = await Promise.all(
    tracks.map(async (track) => {
      try {
        const realCover = await fetchAlbumCover(track.artist, track.album);
        if (realCover) {
          return { ...track, albumArt: realCover };
        }
      } catch (error) {
        console.error(`[v0] Failed to load cover for ${track.artist} - ${track.album}:`, error);
      }
      return track;
    })
  );
  
  return tracksWithCovers;
};

